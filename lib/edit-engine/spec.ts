// Edit spec: the JSON contract between the retention-editor (who decides) and
// the renderer (who executes). A spec is fully resolved: no template slots left.
// Bun only. No dependencies outside the Bun standard library.
import { existsSync, readFileSync } from "node:fs";
import { dirname, isAbsolute, join, resolve } from "node:path";
import { pickSfx, pickTrack, synthAnchor } from "./library.ts";
import { resolveBroll, validateBroll, type BrollSpec } from "./broll.ts";
import { validateReframe, type ReframeSpec } from "./reframe.ts";

export type Platform = "instagram_reels" | "tiktok" | "youtube_shorts" | "facebook_reels";
export type Animation = "none" | "fade" | "pop_in" | "slide_up" | "line_stagger" | "word_reveal";

export interface Rect { x: number; y: number; w: number; h: number }

/** A visual media layer placed on the canvas. Order in `layers` is z-order. */
export interface MediaLayer {
  id: string;
  src: string;
  kind: "image" | "video";
  start: number;          // timeline seconds
  duration: number;       // timeline seconds
  in?: number;            // source offset (video)
  speed?: number;         // 1 = normal; 2 = twice as fast (speed ramp is a sequence of layers)
  rect?: Rect;            // default: full canvas
  fit?: "cover" | "contain";
  crop_focus?: { x?: number; y?: number }; // cover: which part of the overflow stays (0 = left/top, 0.5 = centre, 1 = right/bottom)
  border_px?: number;     // white frame around a slot (screen slot, B-roll window)
  border_color?: string;
  audio?: boolean;        // keep this layer's own audio (talking head)
  framing?: string;       // shot label ("selfie-medium", "wide", "screen"): a dissolve is only legal between different framings
  transition_in?: { type: "cut" | "dissolve"; duration?: number };  // how this layer enters over the previous one (default cut)
  // B-roll (2.1.0): written by resolveSpec from spec.broll, never by hand. A layer with `broll` is drawn above the
  // camera (not zoomed) and under the text; `alpha` = a card clip with transparency (QuickTime Animation, overlay format=auto).
  broll?: string;         // the broll item id it comes from
  alpha?: boolean;
  provenance?: Record<string, unknown>;
  // Cleaned voice (2.2.0): a WAV with the same timeline as `src` (cli.ts cut --denoise, editonny denoise.py);
  // the take keeps its picture from `src` and takes its audio from here.
  audio_src?: string;
}

/**
 * Cuts between consecutive full-frame takes (talking head). Never an image
 * dissolve between takes of the same framing: the two faces blend into a ghost.
 *   jcut_frames      incoming audio starts this many frames before the picture cut (2 to 4)
 *   audio_xfade_ms   micro crossfade on the audio only, at every cut (40 to 80 ms)
 *   punch_alternate  zoom added to every other take (0.06 to 0.08 = 106 to 108%), switched on the cut frame
 */
export interface Transitions { jcut_frames?: number; audio_xfade_ms?: number; punch_alternate?: number }

export type CameraMove =
  | { type: "push"; start: number; end: number; from: number; to: number }
  | { type: "impact"; at: number; amount: number; attack?: number; release?: number }
  | { type: "punch_in"; at: number; until: number; amount: number; auto?: boolean };  // auto = generated by transitions.punch_alternate

export interface Flash { at: number; duration: number; color?: string; opacity?: number }

export interface TextStyle {
  font_family?: string;   // must exist in fontsdir
  font_px: number;
  size_basis?: "line" | "em"; // line (default) = libass size; em = CSS-like em size, converted with the font's metrics (lib/edit-engine/fonts.ts)
  bold?: boolean;
  color?: string;         // #RRGGBB
  highlight_color?: string;
  outline_px?: number;
  outline_color?: string;
  shadow_px?: number;
  box?: boolean;          // opaque box behind the text (ASS BorderStyle 3)
  box_color?: string;
  line_spacing_px?: number; // distance between line centres; used by pop_in, slide_up, fade and none (one event per line)
  uppercase?: boolean;
}

export interface TextLayer {
  id: string;
  role: "hook" | "label" | "caption" | "cta";
  lines: string[];
  start: number;
  end: number;
  x: number;              // centre of the text block
  y: number;
  style: TextStyle;
  animation: Animation;
  stagger?: number;       // seconds between lines/words for line_stagger/word_reveal
  highlight_words?: string[];
  fit_width?: boolean;    // shrink the font until the block fits the safe width
  max_width_px?: number;  // shrink the font until the measured block is at most this wide
  mode?: "fixed" | "intro"; // headline: fixed = whole video (start 0, end = duration); intro = start..end as written (0-3 s)
}

export type CaptionPreset = "classic" | "bold-word";

/** Word-level captions (talking head). Words come from a transcriber, never invented. */
export interface Captions {
  words: { word: string; start: number; end: number; emphasis?: boolean }[];
  style: TextStyle;
  y: number;
  max_words: number;      // words per caption group (a group also ends at , . ! ? ; : or a pause >= 0.3 s)
  highlight_active?: boolean;
  emphasis_color?: string; // keyword colour for words flagged `emphasis` (classic: 110% for the whole group; bold-word: colour only)
  /**
   * classic   = the 1.0 look: active word in highlight_color at 110%.
   * bold-word = condensed caps (Anton), the spoken word grows on entry (pop_scale), keywords in emphasis_color,
   *             each group fitted to max_width_px and held up to 0.25 s into the pause.
   */
  preset?: CaptionPreset;
  pop_scale?: number;      // bold-word: % the spoken word grows to (default 114)
  max_width_px?: number;   // bold-word: widest a group may be (default 860 at 1080 wide)
  group_font_px?: number[]; // written by the render fit (one per caption group); do not hand-edit
  /** written by resolveSpec from spec.broll: a caption group that overlaps a window moves to `y` or hides; do not hand-edit */
  windows?: { start: number; end: number; y?: number; hide?: boolean; broll?: string }[];
}

/**
 * only_with_music: the effect is dropped when the spec has no music bed (a lone whoosh over a dry voice reads loud).
 * src: a path, or "@sfx:<role|category|id>" from assets/sfx/index.json (resolved by resolveSpec; `library` keeps the id).
 * anchor: true = `at` is the second of the audible impact; the file starts anchor_s earlier (written by resolveSpec).
 */
export interface Sfx { src: string; at: number; gain_db?: number; hook?: string; only_with_music?: boolean; anchor?: boolean; anchor_s?: number; library?: string; broll?: string }

/**
 * Background music under the voice. `path` (or the legacy `src`) is the track;
 * `start` is the timeline second it enters; `offset` the second of the track it
 * starts from. Level: `below_voice_db` (measured: the ducked bed ends this many
 * LU under the voice) or a fixed `gain_db`. With voice layers the bed is ducked
 * by an ffmpeg sidechain compressor, at most `duck_db` under speech.
 */
export interface MusicSpec {
  path?: string;          // a file, or "@music:<track id|mood>" from assets/music/index.json
  src?: string;
  mood?: string;          // pick from the squad library by mood (calm, chill-beat, emotional, groove, hiphop, upbeat)
  track?: string;         // with mood: one track id of that mood
  library?: string;       // written by resolveSpec: the library track id used
  start?: number;
  offset?: number;
  gain_db?: number;
  below_voice_db?: number;
  duck_db?: number;
  fade_in_s?: number;
  fade_out_s?: number;
  measured?: Record<string, number | string>;  // written by the render: voice LUFS, gain used, measured gap and ducking
}

export interface AudioSpec {
  music?: MusicSpec;
  sfx: Sfx[];
  mutes?: { start: number; end: number }[];   // silence before the turn
  loudness: { target_lufs: number; true_peak_db: number };
  voice_cleanup?: { highpass_hz?: number };  // high-pass on each layer's own audio before the mix (removes room rumble)
}

/**
 * The measured cut a talking head came from (2.2.0, lib/edit-engine/cut.ts). `holds` are the pauses the
 * cut kept on purpose (pace, or a pause the person asked for), on the timeline: the breaths_remaining QA
 * excuses a silence inside one of them up to `max_s`. `end_hold_s` is the still tail after the last word.
 */
export interface CutInfo {
  file?: string;
  pace?: string;
  holds: { start: number; end: number; max_s: number; why: string }[];
  end_hold_s?: number;
  verify?: Record<string, unknown>;
}

export interface HookApplied { hook: string; at: number; why: string; broll?: string }

export interface EditSpec {
  spec_version: 1;
  id: string;
  template: string;
  canvas: { width: number; height: number; fps: number };
  duration: number;
  platforms: Platform[];
  layers: MediaLayer[];
  transitions?: Transitions;
  camera: CameraMove[];
  camera_focus?: { x: number; y: number };    // 0..1, default centre
  flashes: Flash[];
  texts: TextLayer[];
  captions?: Captions;
  audio: AudioSpec;
  protect_regions?: (Rect & { label: string })[];   // e.g. eyes and mouth: text must not cover
  hooks_applied: HookApplied[];
  alignment: { text: string; visual: string; audio: string };
  frame_at?: number;
  output: { crf: number; preset: string };
  notes?: string[];
  /** Automatic B-roll (2.1.0, lib/edit-engine/broll.ts). Absent or mode "off": the render is the same as before. */
  broll?: BrollSpec;
  /** Measured cut (2.2.0): the pauses kept on purpose, for the breaths_remaining QA. Absent: the QA only reports. */
  cut?: CutInfo;
  /** Reframe a wider source into the canvas (2.2.0, lib/edit-engine/reframe.ts). Absent or mode "off": as before. */
  reframe?: ReframeSpec;
}

export class SpecError extends Error {}

const num = (v: unknown) => typeof v === "number" && Number.isFinite(v);

/** Structural validation. Returns the list of problems; empty means valid. */
export function validateSpec(s: EditSpec): string[] {
  const p: string[] = [];
  if (s.spec_version !== 1) p.push("spec_version must be 1");
  if (!s.id || !/^[a-z0-9][a-z0-9._-]*$/i.test(s.id)) p.push("id must be a filename-safe slug");
  const c = s.canvas;
  if (!c || !num(c.width) || !num(c.height) || !num(c.fps)) p.push("canvas needs width, height, fps");
  if (!num(s.duration) || s.duration <= 0 || s.duration > 180) p.push("duration must be in (0, 180] s");
  if (!Array.isArray(s.layers) || s.layers.length === 0) p.push("at least one media layer");
  for (const l of s.layers ?? []) {
    if (!l.src) p.push(`layer ${l.id}: src missing`);
    else if (!existsSync(l.src)) p.push(`layer ${l.id}: src not found: ${l.src}`);
    if (!num(l.start) || !num(l.duration) || l.duration <= 0) p.push(`layer ${l.id}: start/duration invalid`);
    if (l.start + l.duration > s.duration + 1e-6) p.push(`layer ${l.id}: ends after the video`);
    if (l.speed !== undefined && (l.speed <= 0 || l.speed > 4)) p.push(`layer ${l.id}: speed must be in (0, 4]`);
    if (l.audio_src !== undefined && !existsSync(l.audio_src)) p.push(`layer ${l.id}: audio_src not found: ${l.audio_src}`);
  }
  for (const t of s.texts ?? []) {
    if (!t.lines?.length) p.push(`text ${t.id}: no lines`);
    if (!(t.end > t.start)) p.push(`text ${t.id}: end must be after start`);
    if (t.end > s.duration + 1e-6) p.push(`text ${t.id}: ends after the video`);
    if (!num(t.style?.font_px)) p.push(`text ${t.id}: style.font_px missing`);
  }
  for (const m of s.camera ?? []) {
    if (m.type === "push" && (m.from < 1 || m.to < 1)) p.push("push zoom must stay >= 1");
    if (m.type === "impact" && (m.amount <= 0 || m.amount > 0.3)) p.push("impact amount must be in (0, 0.3]");
  }
  for (const f of s.audio?.sfx ?? []) if (!existsSync(f.src)) p.push(f.src.startsWith("@sfx:") ? `sfx not in the library: ${f.src} (bun lib/edit-engine/cli.ts library sfx)` : `sfx not found: ${f.src}`);
  const m = s.audio?.music;
  if (m) {
    const mp = musicPath(m);
    if (!mp) p.push("audio.music needs path or mood");
    else if (mp.startsWith("@music:")) p.push(`music not in the library: ${mp} (bun lib/edit-engine/cli.ts library music)`);
    else if (!existsSync(mp)) p.push(`music not found: ${mp}`);
    if (m.below_voice_db !== undefined && (m.below_voice_db < 6 || m.below_voice_db > 40)) p.push("audio.music.below_voice_db must be in [6, 40] (20 to 24 is typical)");
    if (m.duck_db !== undefined && (m.duck_db < 0 || m.duck_db > 20)) p.push("audio.music.duck_db must be in [0, 20]");
    if ((m.start ?? 0) >= s.duration - 0.5) p.push("audio.music.start must leave at least 0.5 s of music");
  }
  const tr = s.transitions;
  if (tr) {
    if (tr.jcut_frames !== undefined && (tr.jcut_frames < 0 || tr.jcut_frames > 6)) p.push("transitions.jcut_frames must be in [0, 6] (2 to 4 recommended)");
    if (tr.audio_xfade_ms !== undefined && (tr.audio_xfade_ms < 0 || tr.audio_xfade_ms > 200)) p.push("transitions.audio_xfade_ms must be in [0, 200] (40 to 80 recommended)");
    if (tr.punch_alternate !== undefined && (tr.punch_alternate < 0 || tr.punch_alternate > 0.15)) p.push("transitions.punch_alternate must be in [0, 0.15] (0.06 to 0.08 recommended)");
  }
  for (const g of ghostDissolves(s)) p.push(`layer ${g}: image dissolve between takes of the same framing makes a ghost face; use a cut (set different \`framing\` only when the shots really differ)`);
  for (const l of s.layers ?? []) {
    const d = l.transition_in?.type === "dissolve" ? (l.transition_in.duration ?? 0.3) : 0;
    if (d > 0 && (l.in ?? 0) < d - 1e-6 && l.kind === "video") p.push(`layer ${l.id}: dissolve of ${d} s needs ${d} s of source before \`in\``);
  }
  for (const t of s.texts ?? []) if (t.mode && t.mode !== "fixed" && t.mode !== "intro") p.push(`text ${t.id}: mode must be fixed or intro`);
  if (s.captions?.preset && !["classic", "bold-word"].includes(s.captions.preset)) p.push("captions.preset must be classic or bold-word");
  if (!s.hooks_applied?.length) p.push("hooks_applied is empty: name the catalog hooks this spec uses");
  if (!s.alignment?.text || !s.alignment?.visual || !s.alignment?.audio) p.push("alignment needs text, visual and audio");
  p.push(...validateBroll(s));
  p.push(...validateReframe(s));
  for (const h of s.cut?.holds ?? []) if (!(h.end > h.start) || !(h.max_s > 0)) p.push("cut.holds: every hold needs start < end and max_s > 0");
  return p;
}

export const musicPath = (m?: MusicSpec | null) => (m ? (m.path ?? m.src ?? null) : null);

/** Full-frame video layers in timeline order: the takes of a talking head. */
export function takes(s: EditSpec): MediaLayer[] {
  return (s.layers ?? []).filter((l) => l.kind === "video" && !l.rect && !l.broll).sort((a, b) => a.start - b.start);
}

/** True when `b` starts where `a` ends (within half a frame). */
export function adjacent(a: MediaLayer, b: MediaLayer, fps: number): boolean {
  return Math.abs(a.start + a.duration - b.start) < 0.5 / fps;
}

/** Layers that ask for an image dissolve over a previous take of the same (or undeclared) framing. */
export function ghostDissolves(s: EditSpec): string[] {
  const t = takes(s), out: string[] = [];
  for (let i = 1; i < t.length; i++) {
    if (t[i].transition_in?.type !== "dissolve") continue;
    const a = t[i - 1].framing, b = t[i].framing;
    if (!a || !b || a === b) out.push(t[i].id);
  }
  return out;
}

/**
 * Normalises a spec in place; idempotent, safe to call before every validate,
 * render and QA. Music given as a bare path becomes {path}; music without a path
 * is dropped. A `fixed` headline spans the whole video. transitions.punch_alternate
 * regenerates its punch-ins (every other take, switched on the cut frame). spec.broll becomes its layers,
 * sounds, caption windows and hooks (broll.ts resolveBroll; nothing when it is absent or "off").
 */
export function resolveSpec(s: EditSpec): EditSpec {
  resolveBroll(s);
  const a = s.audio as AudioSpec | undefined;
  if (a) {
    if (typeof a.music === "string") a.music = { path: a.music };
    if (a.music?.src && !a.music.path) { a.music.path = a.music.src; delete a.music.src; }
    resolveLibrary(a);
    if (a.music && !musicPath(a.music)) delete a.music;
  }
  for (const t of s.texts ?? []) if (t.mode === "fixed") { t.start = 0; t.end = s.duration; }
  if (s.camera) {
    s.camera = s.camera.filter((m) => !(m.type === "punch_in" && m.auto));
    const amount = s.transitions?.punch_alternate ?? 0;
    if (amount > 0) {
      takes(s).forEach((l, i) => {
        if (i % 2 === 1) s.camera.push({ type: "punch_in", at: l.start, until: l.start + l.duration, amount, auto: true });
      });
    }
  }
  return s;
}

/**
 * Library names to files (idempotent): "@squad/..." paths, "@music:<id|mood>", music.mood/track,
 * "@sfx:<role|category|id>" and the impact second of anchored effects. An unknown name is left as
 * written, so validation reports it as not found.
 */
export function resolveLibrary(a: AudioSpec): void {
  const m = a.music;
  if (m) {
    if (m.path?.startsWith("@squad/")) m.path = join(SQUAD_ROOT, m.path.slice(7));
    const ref = m.path?.startsWith("@music:") ? m.path.slice(7) : !m.path && m.mood ? m.mood : null;
    if (ref) {
      const t = pickTrack(ref, m.path ? undefined : m.track);
      if (t) { m.path = t.path; m.library = t.id; m.offset ??= t.track.fill_at_s; }
      else if (!m.path) m.path = `@music:${ref}`;
    }
  }
  for (const f of a.sfx ?? []) {
    if (f.src?.startsWith("@squad/")) f.src = join(SQUAD_ROOT, f.src.slice(7));
    if (f.src?.startsWith("@sfx:")) {
      const x = pickSfx(f.src.slice(5));
      if (x) { f.src = x.path; f.library = x.id; if (f.anchor) f.anchor_s = x.anchor_s; }
    } else if (f.anchor && f.anchor_s === undefined && f.src) {
      const sa = synthAnchor(f.src);
      if (sa !== null) f.anchor_s = sa;
    }
  }
}

/** Second the effect file starts on the timeline (can be negative: the head of the file is skipped). */
export const sfxStart = (f: Sfx) => f.at - (f.anchor ? (f.anchor_s ?? 0) : 0);

export function loadSpec(path: string): EditSpec {
  const raw = JSON.parse(readFileSync(path, "utf8")) as EditSpec;
  const base = dirname(resolve(path));
  const abs = (p: string) => (isAbsolute(p) || p.startsWith("@") ? p : resolve(base, p));
  for (const l of raw.layers ?? []) { l.src = abs(l.src); if (l.audio_src) l.audio_src = abs(l.audio_src); }
  for (const f of raw.audio?.sfx ?? []) f.src = abs(f.src);
  if (typeof raw.audio?.music === "string") raw.audio.music = { path: raw.audio.music };
  if (raw.audio?.music?.path) raw.audio.music.path = abs(raw.audio.music.path);
  if (raw.audio?.music?.src) raw.audio.music.src = abs(raw.audio.music.src);
  resolveSpec(raw);
  return raw;
}

export function assertValid(s: EditSpec): void {
  resolveSpec(s);
  const problems = validateSpec(s);
  if (problems.length) throw new SpecError("invalid edit spec:\n- " + problems.join("\n- "));
}

